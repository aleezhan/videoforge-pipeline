"""Окно консоли у дочернего процесса: его быть не должно.

Пульт живёт задачей планировщика под `pythonw` — своей консоли у него НЕТ, и
каждый запущенный им ffmpeg получает от Windows свою собственную: чёрное окно
на долю секунды поверх всего, включая полноэкранную игру. По одному на вызов,
а вызовы идут пачкой: страница «Тесты» снимает обложку каждому ролику, и
шесть обложек 20.09.2026 в 2:46:51…2:46:57 — это шесть окон подряд (жалоба
человека «мигает раз десять», доказательство — время файлов `final.poster.jpg`).

`CREATE_NO_WINDOW` снимает окно и ничего больше: вывод дочернего процесса мы
читаем через пайпы, а не с экрана. Из терминала видно то же самое, что и
раньше — там окно консоли у ffmpeg и так не своё, а унаследованное.

Словарь, а не число, потому что флаг есть только на Windows: на остальных
системах `**NO_WINDOW` не добавляет ничего.
"""

from __future__ import annotations

import os
import subprocess
from typing import Any

NO_WINDOW: dict[str, Any] = (
    {"creationflags": subprocess.CREATE_NO_WINDOW} if os.name == "nt" else {}
)
